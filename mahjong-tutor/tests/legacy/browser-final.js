async (page) => {
  const base='http://127.0.0.1:4198/', out='/Users/chenliangyu/project_cly/gogoGame/mahjong-tutor/output/';
  const results=[];
  const assert=(c,m)=>{if(!c)throw Error(m)};
  await page.goto(base);
  await page.evaluate(()=>localStorage.removeItem('mahjong-tutor.v1'));
  await page.reload();
  await page.goto(base+'#lesson/5');
  await page.locator('[data-action="select"][data-index="1"]').click();
  await page.locator('[data-action="check"]').click();
  await page.locator('.solutions summary').click();
  assert(await page.locator('.solutions .hand-group').count()===5,'winning decomposition');
  await page.setViewportSize({width:375,height:812});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'expanded solution overflow');
  await page.screenshot({path:out+'wait-mobile.png',fullPage:true});
  await page.locator('.skip').focus();
  await page.keyboard.press('Enter');
  assert(page.url().endsWith('#lesson/5'),'skip must preserve lesson route');
  results.push('expanded winning decomposition and skip link');
  await page.locator('[data-action="language"]').click();
  await page.goto(base+'#lesson/4');
  await page.evaluate(()=>Promise.all([...document.images].map(i=>i.decode())));
  assert((await page.locator('.display-tiles .tile-name').first().textContent())==='2 char.','compact English names');
  await page.screenshot({path:out+'calls-mobile-en.png',fullPage:true});
  await page.goto(base+'#lesson/6');
  await page.locator('[data-action="round-draw"]').click();
  for(const width of [320,375]) {
    await page.setViewportSize({width,height:812});
    await page.evaluate(()=>Promise.all([...document.images].map(i=>i.decode())));
    const status=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,images:[...document.images].every(i=>i.complete&&i.naturalWidth>0)}));
    assert(!status.overflow&&status.images,'English round load at '+width);
  }
  results.push('English phone labels and round images at 320/375');
  const browser=page.context().browser();
  const isolated=await browser.newContext({viewport:{width:375,height:812}});
  const tab=await isolated.newPage();
  await tab.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Storage disabled','SecurityError')}}));
  await tab.goto(base);
  assert(await tab.locator('.save-status.warning').isVisible(),'storage denied notice');
  await tab.locator('[data-action="resume"]').click();
  await tab.locator('[data-action="select"][data-index="1"]').click();
  await tab.locator('[data-action="check"]').click();
  await tab.locator('[data-action="next"]').click();
  assert((await tab.locator('.question-count').textContent()).includes('02'),'storage denied remains playable');
  await isolated.close();
  results.push('blocked localStorage remains playable');
  const corrupt=await browser.newContext();
  const tab2=await corrupt.newPage();
  await tab2.goto(base);
  await tab2.evaluate(()=>localStorage.setItem('mahjong-tutor.v1','{broken'));
  await tab2.reload();
  assert(await tab2.locator('[data-action="resume"]').isVisible(),'corrupt progress recovers');
  await corrupt.close();
  results.push('corrupt progress recovers');
  await page.evaluate(()=>localStorage.removeItem('mahjong-tutor.v1'));
  await page.goto(base+'#home');
  await page.reload();
  await page.setViewportSize({width:1440,height:1050});
  return {passed:results};
}
