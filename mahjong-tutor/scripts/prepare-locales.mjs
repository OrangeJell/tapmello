import { readFile, writeFile } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const interfaceCopy=JSON.parse(await readFile(new URL('js/interface-hi.json',root),'utf8'));
const articleCopy=JSON.parse(await readFile(new URL('js/articles-hi.json',root),'utf8'));
const copy={...interfaceCopy,...articleCopy};
await writeFile(new URL('js/hi.js',root),'// Generated by scripts/prepare-locales.mjs from the reviewed Hindi content assets.\nexport const hindi = '+JSON.stringify(copy,null,2)+';\n');
console.log(`Prepared ${Object.keys(copy).length} Hindi strings.`);
